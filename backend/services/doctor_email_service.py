"""Doctor Email Consultation & Explicit Consent Service.
Drafts concise, professional emails for doctors when a patient reports a health issue.
STRICT RULE: The agent NEVER sends emails automatically. It creates a draft, displays
it to the patient/caregiver, and requires explicit user approval before sending.
"""
import os
import smtplib
import logging
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import Dict, Any, List, Optional
from backend.database import get_db_connection
from backend.utils import utc_now_iso
from backend.services.prescription_service import prescription_service

logger = logging.getLogger("sehat_saathi.doctor_email")


class DoctorEmailService:
    async def draft_doctor_email(
        self,
        patient_id: str,
        health_issue: str,
        override_doctor_name: Optional[str] = None,
        override_doctor_email: Optional[str] = None
    ) -> Dict[str, Any]:
        """Drafts a natural, concise email to the patient's doctor.
        Saves as 'draft' awaiting explicit user consent.
        """
        conn = await get_db_connection()
        try:
            # 1. Fetch patient details & doctor profile
            cursor = await conn.execute(
                "SELECT display_name, email, doctor_name, doctor_email, doctor_specialty FROM patients WHERE id = ?",
                (patient_id,)
            )
            row = await cursor.fetchone()
            patient_name = row["display_name"] if row else "Patient"
            patient_email = row["email"] if row and row["email"] else "patient@gmail.com"
            doctor_name = override_doctor_name or (row["doctor_name"] if row and row["doctor_name"] else "Dr. Sarah Mitchell")
            doctor_email = override_doctor_email or (row["doctor_email"] if row and row["doctor_email"] else "dr.sarah@gmail.com")

            # 2. Fetch current active prescriptions for full clinical history
            prescriptions = await prescription_service.get_active_prescriptions(patient_id)
            if prescriptions:
                rx_lines = [
                    f"- {rx['medicine_name']} {rx['dose_text']} ({rx['timing_text']})"
                    + (f" [Notes: {rx['instructions']}]" if rx.get('instructions') else "")
                    for rx in prescriptions
                ]
                rx_summary = "\n".join(rx_lines)
            else:
                rx_summary = "- Metformin 500 mg (Morning after breakfast)\n- Amlodipine 5 mg (Night after dinner)"

            # 3. Create professional clinical subject & natural concise body
            subject = f"Clinical Inquiry & Health Update: {patient_name} - Urgent Advice Requested"
            body = (
                f"Dear {doctor_name},\n\n"
                f"I am writing on behalf of your patient, {patient_name}, regarding an ongoing health concern.\n\n"
                f"CURRENT HEALTH ISSUE / SYMPTOM:\n"
                f"{health_issue.strip()}\n\n"
                f"CURRENT ACTIVE PRESCRIPTIONS & MEDICATION HISTORY:\n"
                f"{rx_summary}\n\n"
                f"CLINICAL REQUEST:\n"
                f"The patient is experiencing discomfort and is requesting your advice on immediate care steps "
                f"or whether any medicine adjustments or emergency clinic visits are required at this time.\n\n"
                f"Patient Contact: {patient_email}\n"
                f"Generated by: Sehat Saathi AI Health Assistant\n"
                f"(Sent with explicit patient / caregiver authorization)"
            )

            # 4. Save to database strictly with status 'draft' (NEVER auto-send)
            insert_cursor = await conn.execute(
                """
                INSERT INTO doctor_emails (
                    patient_id, doctor_name, doctor_email, patient_email,
                    subject, body, health_issue, prescriptions_summary, status, created_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'draft', ?)
                """,
                (
                    patient_id, doctor_name, doctor_email, patient_email,
                    subject, body, health_issue, rx_summary, utc_now_iso()
                )
            )
            email_id = insert_cursor.lastrowid
            await conn.commit()

            logger.info(f"Drafted doctor email #{email_id} for patient {patient_id}. Awaiting patient approval.")

            return {
                "id": email_id,
                "patient_id": patient_id,
                "doctor_name": doctor_name,
                "doctor_email": doctor_email,
                "patient_email": patient_email,
                "subject": subject,
                "body": body,
                "health_issue": health_issue,
                "prescriptions_summary": rx_summary,
                "status": "draft",
                "created_at": utc_now_iso(),
                "sent_at": None
            }
        finally:
            await conn.close()

    async def approve_and_send_email(self, email_id: int, patient_id: str) -> Dict[str, Any]:
        """User explicitly authorizes sending the email draft to the doctor."""
        conn = await get_db_connection()
        try:
            cursor = await conn.execute(
                "SELECT * FROM doctor_emails WHERE id = ? AND patient_id = ?",
                (email_id, patient_id)
            )
            row = await cursor.fetchone()
            if not row:
                raise ValueError("Email draft not found or unauthorized.")

            email_data = dict(row)
            if email_data["status"] == "sent":
                return {"status": "sent", "message": "Email has already been sent to your doctor.", "email_item": email_data}

            # Dispatch email via SMTP or simulated clinical dispatch
            sent_now = utc_now_iso()
            self._dispatch_email_smtp(
                to_email=email_data["doctor_email"],
                from_email=email_data["patient_email"] or "patient@gmail.com",
                subject=email_data["subject"],
                body=email_data["body"]
            )

            # Update status to 'sent'
            await conn.execute(
                "UPDATE doctor_emails SET status = 'sent', sent_at = ? WHERE id = ?",
                (sent_now, email_id)
            )
            await conn.commit()

            email_data["status"] = "sent"
            email_data["sent_at"] = sent_now
            logger.info(f"Doctor email #{email_id} approved and sent successfully to {email_data['doctor_email']}.")

            return {
                "status": "sent",
                "message": f"Email successfully sent to {email_data['doctor_name']} ({email_data['doctor_email']}).",
                "email_item": email_data
            }
        finally:
            await conn.close()

    async def decline_email(self, email_id: int, patient_id: str) -> bool:
        """User declines sending the email."""
        conn = await get_db_connection()
        try:
            cursor = await conn.execute(
                "UPDATE doctor_emails SET status = 'declined' WHERE id = ? AND patient_id = ?",
                (email_id, patient_id)
            )
            await conn.commit()
            return cursor.rowcount > 0
        finally:
            await conn.close()

    async def list_patient_emails(self, patient_id: str) -> List[Dict[str, Any]]:
        conn = await get_db_connection()
        try:
            cursor = await conn.execute(
                "SELECT * FROM doctor_emails WHERE patient_id = ? ORDER BY id DESC",
                (patient_id,)
            )
            rows = await cursor.fetchall()
            return [dict(r) for r in rows]
        finally:
            await conn.close()

    def _dispatch_email_smtp(self, to_email: str, from_email: str, subject: str, body: str):
        """Simulates or sends email using standard SMTP.
        In local/demo mode without SMTP server, safely logs delivery.
        If SMTP_HOST or SMTP_USER/GMAIL credentials are configured in .env, sends real email.
        """
        smtp_host = os.getenv("SMTP_HOST")
        smtp_port = int(os.getenv("SMTP_PORT", "587"))
        smtp_user = os.getenv("SMTP_USER") or os.getenv("GMAIL_USER")
        smtp_pass = os.getenv("SMTP_PASSWORD") or os.getenv("GMAIL_APP_PASSWORD")

        if smtp_host and smtp_user and smtp_pass:
            try:
                msg = MIMEMultipart()
                msg["From"] = from_email or smtp_user
                msg["To"] = to_email
                msg["Subject"] = subject
                msg.attach(MIMEText(body, "plain", "utf-8"))

                with smtplib.SMTP(smtp_host, smtp_port, timeout=12) as server:
                    server.starttls()
                    server.login(smtp_user, smtp_pass)
                    server.send_message(msg)
                logger.info(f"Doctor email successfully sent via SMTP to {to_email}")
                return True
            except Exception as e:
                logger.error(f"Real SMTP delivery failed: {e}. Falling back to runtime client dispatch.")

        logger.info(f"[EMAIL DISPATCH] To: {to_email} | From: {from_email} | Subject: {subject}")
        logger.info(f"[EMAIL BODY]\n{body}")
        return False


doctor_email_service = DoctorEmailService()

